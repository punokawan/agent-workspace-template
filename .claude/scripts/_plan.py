#!/usr/bin/env python3
"""Planning index + drift detection. Frontmatter is the single source of truth.

Scoped to one project at a time: every project keeps its own planning/ tree and its
own INDEX.md. With no --project, commands run across every registered project.
"""
import os, re, sys, json, subprocess, datetime

sys.dont_write_bytecode = True   # keep __pycache__ out of the toolkit tree
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _project

ROOT = _project.ROOT
STATUSES = ["draft", "scoped", "in-progress", "partial", "shipped", "dropped", "needs-review"]
DONE = {"shipped", "partial"}
UNBUILT = {"draft", "scoped"}
C = dict(r="\033[31m", g="\033[32m", y="\033[33m", c="\033[36m", b="\033[1m", x="\033[0m")

# ------------------------------------------------------------ project scoping

PROJECT = ""          # set by run(); the project whose planning tree we are reading
PLAN = ""             # absolute path to that project's planning dir


def set_project(name):
    """Point the module at one project's planning tree."""
    global PROJECT, PLAN
    man = _project.load_project(name)
    PROJECT = name
    PLAN = os.path.join(man["_dir"], man.get("planning") or "planning")
    return man


def target_projects(argv):
    """--project <name> selects one; otherwise every project that has a planning dir."""
    if "--project" in argv:
        i = argv.index("--project")
        return [argv[i + 1]], [a for j, a in enumerate(argv) if j not in (i, i + 1)]
    names = []
    for n in _project.project_names():
        man = _project.load_project(n)
        if os.path.isdir(os.path.join(man["_dir"], man.get("planning") or "planning")):
            names.append(n)
    return names, argv


def load():
    out = []
    for d in ("features", "improvements"):
        dp = os.path.join(PLAN, d)
        if not os.path.isdir(dp): continue
        for fn in sorted(os.listdir(dp)):
            if not fn.endswith(".md"): continue
            p = os.path.join(dp, fn)
            t = open(p, encoding="utf-8").read()
            if not t.startswith("---\n"): continue
            try: block = t[4:t.index("\n---\n", 3)]
            except ValueError: continue
            m = {}
            for line in block.splitlines():
                if ": " in line:
                    k, v = line.split(": ", 1)
                    m[k.strip()] = v.strip().strip('"')
            m["_path"] = os.path.relpath(p, PLAN)
            out.append(m)
    return out

def grep_code(needle):
    """How many real source files mention this symbol (excludes generated + vendored).

    Which extensions count as source, and which filenames are generated, come from each
    repo's stack preset — so a new language is covered without touching this function.
    """
    if not needle: return 0
    n = 0
    for repo in _project.load_project(PROJECT)["repos"]:
        rp = repo["dir"]
        if not os.path.isdir(rp): continue
        includes = []
        for ext in repo.get("code_ext", []):
            includes += ["--include", "*" + ext]
        if not includes: continue
        try:
            res = subprocess.run(["grep", "-rl"] + includes + ["-F", needle, rp],
                                 capture_output=True, text=True, timeout=90).stdout.splitlines()
        except Exception:
            continue
        markers = repo.get("generated_markers", []) + ["node_modules", "/vendor/",
                                                       "app_localization"]
        n += len([f for f in res if not any(m in f for m in markers)])
    return n

def cmd_index(argv):
    rows = load()
    by_status, by_area = {}, {}
    for r in rows:
        by_status.setdefault(r.get("status", "?"), []).append(r)
        by_area.setdefault(r.get("area", "general"), []).append(r)
    L = []
    title = _project.load_project(PROJECT).get("title", PROJECT)
    L.append("<!-- GENERATED by .claude/scripts/plan.sh index — DO NOT EDIT BY HAND -->")
    L.append(f"# {title} — Plan Index\n")
    L.append(f"_{len(rows)} plans · regenerate with "
             f"`bash .claude/scripts/plan.sh index --project {PROJECT}`_\n")
    L.append("## By status\n")
    L.append("| Status | Count |")
    L.append("|---|---|")
    for s in STATUSES:
        if s in by_status: L.append(f"| `{s}` | {len(by_status[s])} |")
    L.append("")
    for area in sorted(by_area):
        L.append(f"## {area}\n")
        L.append("| Plan | Type | Status | Ships as | Updated |")
        L.append("|---|---|---|---|---|")
        for r in sorted(by_area[area], key=lambda x: (x.get("status", ""), x.get("id", ""))):
            L.append("| [{}]({}) | {} | `{}` | {} | {} |".format(
                r.get("title", r.get("id")), r["_path"], r.get("type", ""),
                r.get("status", ""), f"`{r['ships_as']}`" if r.get("ships_as") else "—",
                r.get("updated", "")))
        L.append("")
    text = "\n".join(L) + "\n"
    target = os.path.join(PLAN, "INDEX.md")
    if "--check" in argv:
        cur = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
        if cur != text:
            print(f"{C['r']}INDEX.md is stale{C['x']} — run: bash .claude/scripts/plan.sh index"); return 1
        print(f"{C['g']}INDEX.md is current{C['x']}"); return 0
    open(target, "w", encoding="utf-8").write(text)
    print(f"{C['g']}wrote{C['x']} {os.path.relpath(target, ROOT)} ({len(rows)} plans)")
    return 0

def cmd_audit(argv):
    rows = load()
    problems, unverifiable = [], []
    verbose = "--verbose" in argv
    for r in rows:
        st, sid = r.get("status", ""), r.get("id", "?")
        if st not in STATUSES:
            problems.append(("BAD-STATUS", sid, f"'{st}' is not a valid status")); continue
        if st == "needs-review":
            problems.append(("REVIEW", sid, "status was never determined")); continue
        ships = r.get("ships_as", "")
        if st in UNBUILT and ships:
            hits = grep_code(ships)
            if hits:
                problems.append(("UNDERSTATED", sid,
                    f"status '{st}' but '{ships}' appears in {hits} source file(s) — likely shipped"))
        if st == "shipped" and not ships and r.get("type") != "tech-plan":
            unverifiable.append(sid)
    ids = {r.get("id") for r in rows}
    for r in rows:
        p = r.get("parent")
        if p and p not in ids:
            problems.append(("ORPHAN", r.get("id"), f"parent '{p}' does not exist"))
    print(f"{C['b']}PLANNING AUDIT{C['x']} — {len(rows)} plans")
    print("=" * 58)
    if unverifiable:
        print(f"  {C['c']}note{C['x']}  {len(unverifiable)} shipped plan(s) have no `ships_as:` — "
              f"they cannot be auto-verified.")
        print(f"        add one as you touch each file; run with --verbose to list them.")
        if verbose:
            for sid in unverifiable: print(f"          {sid}")
        print()
    if not problems:
        print(f"  {C['g']}PASS{C['x']}  no drift detected")
        print(f"\n{C['g']}VERDICT: CONSISTENT{C['x']}"); return 0
    order = {"UNDERSTATED": 0, "BAD-STATUS": 1, "ORPHAN": 2, "REVIEW": 3, "NO-EVIDENCE": 4}
    for kind, sid, msg in sorted(problems, key=lambda x: order.get(x[0], 9)):
        col = C["r"] if kind in ("UNDERSTATED", "BAD-STATUS", "ORPHAN") else C["y"]
        print(f"  {col}{kind:<12}{C['x']} {sid}: {msg}")
    hard = sum(1 for k, _, _ in problems if k in ("UNDERSTATED", "BAD-STATUS", "ORPHAN"))
    print(f"\n  {len(problems)} finding(s), {hard} blocking")
    print(f"{C['r']}VERDICT: DRIFT{C['x']}" if hard else f"{C['y']}VERDICT: ADVISORY{C['x']}")
    return 1 if hard else 0

def cmd_list(argv):
    rows = load()
    for a in argv:
        if a.startswith("area="): rows = [r for r in rows if r.get("area") == a[5:]]
        elif a.startswith("type="): rows = [r for r in rows if r.get("type") == a[5:]]
        elif a in STATUSES: rows = [r for r in rows if r.get("status") == a]
    for r in sorted(rows, key=lambda x: (x.get("area", ""), x.get("id", ""))):
        print(f"  {r.get('status',''):<13} {r.get('area',''):<14} {r.get('id','')}")
    print(f"\n  {len(rows)} plan(s)")
    return 0

def cmd_set(argv):
    if len(argv) < 2: print("usage: plan.sh set <id> <status> [note]"); return 2
    pid, new = argv[0], argv[1]
    note = " ".join(argv[2:]) if len(argv) > 2 else None
    if new not in STATUSES: print(f"invalid status '{new}' (use: {', '.join(STATUSES)})"); return 2
    for r in load():
        if r.get("id") != pid: continue
        p = os.path.join(PLAN, r["_path"]); t = open(p, encoding="utf-8").read()
        end = t.index("\n---\n", 3) + 5
        fm, body = t[:end], t[end:]
        fm = re.sub(r"^status: .*$", f"status: {new}", fm, flags=re.M)
        fm = re.sub(r"^updated: .*$", f"updated: {datetime.date.today().isoformat()}", fm, flags=re.M)
        if note:
            safe = json.dumps(note, ensure_ascii=False)
            fm = (re.sub(r"^status_note: .*$", f"status_note: {safe}", fm, flags=re.M)
                  if "status_note:" in fm else fm[:-5] + f"\nstatus_note: {safe}\n---\n")
        open(p, "w", encoding="utf-8").write(fm + body)
        print(f"  {pid}: status -> {new}")
        return 0
    print(f"  no plan with id '{pid}'"); return 1

def run(cmd, argv):
    """Run one subcommand over every targeted project, returning the worst exit code."""
    fn = {"index": cmd_index, "audit": cmd_audit, "list": cmd_list, "set": cmd_set}[cmd]
    names, rest = target_projects(argv)
    if not names:
        print("no project has a planning/ directory", file=sys.stderr)
        return 2
    # `set` mutates exactly one plan. A plan id is only unique *within* a project, so fanning
    # out across projects silently rewrites a same-named plan elsewhere — that has happened
    # to a real plan. Resolve to one project or refuse.
    if cmd == "set" and len(names) > 1:
        pid = rest[0] if rest else None
        owners = []
        for name in names:
            try:
                set_project(name)
            except _project.ManifestError:
                continue
            if any(p.get("id") == pid for p in load()):
                owners.append(name)
        if not owners:
            print(f"  no plan with id '{pid}' in any project", file=sys.stderr)
            return 1
        if len(owners) > 1:
            print(f"{C['r']}ambiguous:{C['x']} plan id '{pid}' exists in "
                  f"{', '.join(owners)}.\n  Pass --project <name> to say which one you mean.",
                  file=sys.stderr)
            return 2
        names = owners

    worst = 0
    for i, name in enumerate(names):
        try:
            set_project(name)
        except _project.ManifestError as exc:
            print(f"{C['r']}manifest error:{C['x']} {exc}", file=sys.stderr)
            worst = max(worst, 2)
            continue
        if len(names) > 1:
            if i: print()
            print(f"{C['c']}── {name}{C['x']}")
        worst = max(worst, fn(rest) or 0)
    return worst


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "index"
    sys.exit(run(cmd, sys.argv[2:]))
