#!/usr/bin/env python3
"""Render rule modules into the guides that Claude Code and Codex read.

templates/rules/core/*.md      always on; rendered into the root AGENTS.md
templates/rules/optional/*.md  chosen per project; rendered into projects/<p>/AGENTS.md
templates/rules/profiles.json  core list, named profiles, and the default for new projects
projects/<p>/project.json      "rules": {"profile": "...", "enable": [...], "disable": [...]}

Codex has no import, so the chosen text is written into each AGENTS.md between markers.
"""
import json, os, sys
from datetime import date

ROOT = os.environ.get("STUDIO_ROOT") or os.path.abspath(
    os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
RULES = os.path.join(ROOT, "templates", "rules")
PROJECTS = os.path.join(ROOT, "projects")
BEGIN = "<!-- BEGIN:rules"
END = "<!-- END:rules -->"


def cfg():
    return json.load(open(os.path.join(RULES, "profiles.json"), encoding="utf-8"))


def module(kind, name):
    path = os.path.join(RULES, kind, name + ".md")
    if not os.path.isfile(path):
        raise SystemExit(f"rules: no {kind} module '{name}' — see templates/rules/{kind}/")
    return open(path, encoding="utf-8").read().strip() + "\n"


def optional_names():
    d = os.path.join(RULES, "optional")
    return sorted(f[:-3] for f in os.listdir(d) if f.endswith(".md"))


def projects():
    # Includes _example: a reference project still shows a rendered block.
    return sorted(d for d in os.listdir(PROJECTS)
                  if os.path.isfile(os.path.join(PROJECTS, d, "project.json")))


def manifest(p):
    return json.load(open(os.path.join(PROJECTS, p, "project.json"), encoding="utf-8"))


def chosen(p):
    c = cfg()
    r = manifest(p).get("rules") or {"profile": c["default"]}
    profile = r.get("profile", c["default"])
    if profile not in c["profiles"]:
        raise SystemExit(f"rules: {p} asks for unknown profile '{profile}' "
                         f"(have: {', '.join(c['profiles'])})")
    # The profile's own order stands; modules switched on top of it follow in strict's order.
    names = [n for n in c["profiles"][profile] if n not in r.get("disable", [])]
    order = c["profiles"]["strict"]
    extra = sorted((n for n in r.get("enable", []) if n not in names),
                   key=lambda n: (order.index(n) if n in order else len(order), n))
    return profile, names + extra


def origin():
    src = cfg().get("source")
    return f"[agent-workspace-template]({src})" if src else "the workspace template"


def root_block():
    head = (f"{BEGIN} — core, generated by `bash .claude/scripts/rules.sh sync` from "
            "templates/rules/core/; edit there -->\n")
    note = (f"_Core rules, generated from {origin()} (`templates/rules/core/`). Every project "
            "guide below this file adds its own profile. Edit the modules, then run "
            "`bash .claude/scripts/rules.sh sync`._\n\n")
    return head + note + "\n".join(module("core", n) for n in cfg()["core"]) + END + "\n"


def project_block(p):
    profile, names = chosen(p)
    head = (f"{BEGIN} — generated by `bash .claude/scripts/rules.sh sync` from "
            "templates/rules/optional/; change the profile in project.json -->\n")
    intro = (f"## Rules: {profile} profile\n\n"
             "_Parent: the workspace guide `../../AGENTS.md`, whose core rules always apply. "
             f"Modules generated from {origin()} (`templates/rules/optional/`)._\n\n")
    if names:
        intro += (f"Modules on: {', '.join(names)}. Change them with "
                  f"`bash .claude/scripts/rules.sh set|enable|disable {p} …`.\n")
    else:
        intro += "No optional modules: only the workspace core rules apply.\n"
    body = "".join("\n" + module("optional", n) for n in names)
    return head + intro + body + END + "\n"


def splice(path, block):
    text = open(path, encoding="utf-8").read()
    if BEGIN in text:
        a = text.index(BEGIN)
        if END not in text[a:]:
            raise SystemExit(f"rules: {os.path.relpath(path, ROOT)} has a BEGIN:rules marker but no "
                             f"'{END}' after it — restore that line, then run sync")
        b = text.index(END, a) + len(END)
        new = text[:a] + block.rstrip("\n") + text[b:]
    else:
        # First render: put the block before the guide's first section.
        i = text.find("\n## ")
        i = len(text) if i == -1 else i + 1
        new = text[:i] + block + "\n" + text[i:]
    return text, new


def targets(only=None):
    out = [] if only else [(os.path.join(ROOT, "AGENTS.md"), root_block())]
    for p in ([only] if only else projects()):
        g = os.path.join(PROJECTS, p, "AGENTS.md")
        if os.path.isfile(g):
            out.append((g, project_block(p)))
    return out


def unguided():
    return [p for p in projects() if not os.path.isfile(os.path.join(PROJECTS, p, "AGENTS.md"))]


def sync(check=False, only=None):
    stale = [f"projects/{p} (no AGENTS.md — run: rules.sh adopt {p})" for p in unguided() if not only or p == only]
    for path, block in targets(only):
        old, new = splice(path, block)
        if old != new:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, "w", encoding="utf-8").write(new)
    if check:
        if stale:
            print("rules blocks are stale: " + ", ".join(stale) + " — run: bash .claude/scripts/rules.sh sync")
            return 1
        print("rules blocks are current")
        return 0
    print("synced: " + (", ".join(stale) if stale else "nothing changed"))
    return 0


def edit(p, fn):
    if p not in projects():
        raise SystemExit(f"rules: no project '{p}'")
    path = os.path.join(PROJECTS, p, "project.json")
    man = manifest(p)
    r = man.setdefault("rules", {"profile": cfg()["default"]})
    fn(r)
    for k in ("enable", "disable"):
        if k in r and not r[k]:
            del r[k]
    json.dump(man, open(path, "w", encoding="utf-8"), indent=2)
    open(path, "a", encoding="utf-8").write("\n")
    return sync(only=p)


def adopt(p, profile=None):
    """Bring an existing or freshly pulled project onto AGENTS.md and a rule profile."""
    if p not in projects():
        raise SystemExit(f"rules: projects/{p}/project.json is missing — register it first: "
                         f"bash .claude/scripts/project.sh new {p}")
    d = os.path.join(PROJECTS, p)
    agents, claude = os.path.join(d, "AGENTS.md"), os.path.join(d, "CLAUDE.md")
    if not os.path.isfile(agents):
        old = open(claude, encoding="utf-8").read() if os.path.isfile(claude) else ""
        if old.strip() and old.strip() != "@AGENTS.md":
            os.rename(claude, agents)            # keep the guide it already has, verbatim
            print(f"moved projects/{p}/CLAUDE.md to AGENTS.md")
        else:
            man = manifest(p)
            t = open(os.path.join(ROOT, "templates", "project", "AGENTS.md.tmpl"), encoding="utf-8").read()
            for k, v in (("NAME", p), ("TITLE", man.get("title", p)),
                         ("DESCRIPTION", man.get("description", "")),
                         ("DATE", date.today().isoformat())):
                t = t.replace("{{%s}}" % k, v)
            open(agents, "w", encoding="utf-8").write(t)
            print(f"wrote projects/{p}/AGENTS.md from the template")
        open(claude, "w", encoding="utf-8").write("@AGENTS.md\n")
    if profile or "rules" not in manifest(p):
        new = profile or cfg()["default"]
        if new not in cfg()["profiles"]:
            raise SystemExit(f"rules: unknown profile '{new}'")
        return edit(p, lambda r: r.update(profile=new))
    return sync()


BUILTIN = ("light", "standard", "strict")


def save_cfg(c):
    path = os.path.join(RULES, "profiles.json")
    json.dump(c, open(path, "w", encoding="utf-8"), indent=2)
    open(path, "a", encoding="utf-8").write("\n")


def profile_cmd(argv):
    """Custom profiles beside the three built-ins, which stay fixed so their names mean one thing."""
    c = cfg()
    sub, name = (argv + [None, None])[:2]
    if not sub or not name:
        raise SystemExit("usage: rules.sh profile new <name> [from <profile>] | add|remove <name> <module>"
                         " | delete <name>")
    import re
    if sub == "new":
        if not re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", name):
            raise SystemExit(f"rules: profile name must be kebab-case: '{name}'")
        if name in c["profiles"]:
            raise SystemExit(f"rules: profile '{name}' already exists")
        base = argv[3] if len(argv) == 4 and argv[2] == "from" else None
        if base and base not in c["profiles"]:
            raise SystemExit(f"rules: unknown profile '{base}'")
        c["profiles"][name] = list(c["profiles"][base]) if base else []
        save_cfg(c)
        print(f"profile '{name}' created" + (f" from '{base}'" if base else " (empty)") +
              f": {', '.join(c['profiles'][name]) or '—'}")
        return 0
    if name not in c["profiles"]:
        raise SystemExit(f"rules: unknown profile '{name}'")
    if name in BUILTIN:
        raise SystemExit(f"rules: '{name}' is built in and stays fixed — copy it instead: "
                         f"rules.sh profile new my-{name} from {name}")
    if sub in ("add", "remove"):
        if len(argv) != 3:
            raise SystemExit(f"usage: rules.sh profile {sub} <name> <module>")
        mod = argv[2]
        if mod not in optional_names():
            raise SystemExit(f"rules: no module '{mod}' (have: {', '.join(optional_names())})")
        mods = c["profiles"][name]
        if sub == "add" and mod not in mods:
            mods.append(mod)
        if sub == "remove" and mod in mods:
            mods.remove(mod)
        save_cfg(c)
        print(f"profile '{name}': {', '.join(mods) or '—'}")
        return sync()
    if sub == "delete":
        users = [p for p in projects() if (manifest(p).get("rules") or {}).get("profile") == name]
        if users or c["default"] == name:
            raise SystemExit(f"rules: '{name}' is still used by " +
                             ", ".join(users + (["new projects (default)"] if c["default"] == name else [])))
        del c["profiles"][name]
        save_cfg(c)
        print(f"profile '{name}' deleted")
        return 0
    raise SystemExit(f"rules: unknown profile command '{sub}'")


def main(argv):
    cmd = argv[0] if argv else "list"
    if cmd == "sync":
        if len(argv) == 2 and argv[1] not in projects():
            raise SystemExit(f"rules: no project '{argv[1]}'")
        return sync(only=argv[1] if len(argv) == 2 else None)
    if cmd == "check":
        return sync(check=True)
    if cmd == "list":
        c = cfg()
        print(f"core (always): {', '.join(c['core'])}")
        for name, mods in c["profiles"].items():
            mark = "  (default for new projects)" if name == c["default"] else ""
            mark += "" if name in BUILTIN else "  (custom)"
            print(f"profile {name:<9} {', '.join(mods) or '—'}{mark}")
        print(f"modules: {', '.join(optional_names())}")
        for p in projects():
            profile, names = chosen(p)
            note = "" if "rules" in manifest(p) else "  (not set: default)"
            guide = "" if os.path.isfile(os.path.join(PROJECTS, p, "AGENTS.md")) else "  NO AGENTS.md — run: rules.sh adopt " + p
            print(f"  {p:<16} {profile:<9} {', '.join(names) or '—'}{note}{guide}")
        return 0
    if cmd == "set" and len(argv) == 3:
        p, profile = argv[1], argv[2]
        if profile not in cfg()["profiles"]:
            raise SystemExit(f"rules: unknown profile '{profile}'")
        return edit(p, lambda r: (r.update(profile=profile), r.pop("enable", None), r.pop("disable", None)))
    if cmd in ("enable", "disable") and len(argv) == 3:
        p, name = argv[1], argv[2]
        if name not in optional_names():
            raise SystemExit(f"rules: no module '{name}' (have: {', '.join(optional_names())})")
        other = "disable" if cmd == "enable" else "enable"

        def change(r):
            r.setdefault(cmd, [])
            if name not in r[cmd]:
                r[cmd].append(name)
            if name in r.get(other, []):
                r[other].remove(name)
        return edit(p, change)
    if cmd == "profile":
        return profile_cmd(argv[1:])
    if cmd == "adopt" and len(argv) in (2, 3):
        return adopt(argv[1], argv[2] if len(argv) == 3 else None)
    if cmd == "default" and len(argv) == 2:
        c = cfg()
        if argv[1] not in c["profiles"]:
            raise SystemExit(f"rules: unknown profile '{argv[1]}'")
        c["default"] = argv[1]
        save_cfg(c)
        print(f"new projects start on '{argv[1]}'")
        return 0
    print("usage: rules.sh {list | sync [project] | check | set <project> <profile> |"
          " enable|disable <project> <module> | adopt <project> [profile] | default <profile> |"
          " profile new|add|remove|delete …}")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
