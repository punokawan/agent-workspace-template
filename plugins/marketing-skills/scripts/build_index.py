#!/usr/bin/env python3
"""Rebuild the skill table in README.md from each skills/<name>/SKILL.md frontmatter.

Usage: python3 scripts/build_index.py [plugin_dir]   (default: the folder above this script)
Rewrites only the block between <!-- SKILLS:START --> and <!-- SKILLS:END --> in README.md.
"""
import os
import re
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), '..'))
README = os.path.join(ROOT, 'README.md')
START, END = '<!-- SKILLS:START -->', '<!-- SKILLS:END -->'

CATEGORIES = [
    ('Foundations and strategy', ['product-marketing', 'marketing-ops', 'marketing-plan', 'marketing-council',
                                  'marketing-ideas', 'marketing-loops', 'marketing-psychology', 'customer-research',
                                  'marketing-strategy-pmm', 'brand-guidelines', 'business-name-fit', 'offers',
                                  'competitor-profiling', 'reverse-engineer-marketing', 'ai-decision-authority']),
    ('Conversion (CRO)', ['cro', 'signup', 'onboarding', 'popups', 'paywalls', 'ab-testing', 'lead-magnets']),
    ('Copy and content', ['copywriting', 'copy-editing', 'content-strategy', 'content-production',
                          'content-humanizer', 'prompt-engineer-toolkit']),
    ('SEO and AI search', ['seo-audit', 'ai-seo', 'schema', 'programmatic-seo', 'site-architecture',
                           'local-seo-manager', 'link-building', 'directory-submissions']),
    ('Paid and measurement', ['ads', 'ad-creative', 'analytics', 'conversion-tracking', 'attribution',
                              'campaign-analytics', 'marketing-demand-acquisition']),
    ('Channels', ['emails', 'cold-email', 'sms', 'social', 'social-media-analyzer', 'x-twitter-growth',
                  'community-marketing', 'influencer-marketing', 'public-relations', 'co-marketing', 'events',
                  'video', 'youtube-full', 'image']),
    ('Growth and retention', ['pricing', 'referrals', 'free-tools', 'launch', 'churn-prevention', 'aso']),
    ('Sales and go-to-market', ['competitors', 'sales-enablement', 'prospecting', 'revops']),
]


def read_meta(path):
    text = open(path, encoding='utf-8').read()
    end = text.find('\n---', 4)
    block = text[4:end] if text.startswith('---\n') and end > 0 else ''
    desc = re.search(r'^description:\s*(.+)$', block, re.M)
    sources = re.search(r'^\s+sources:\s*(.+)$', block, re.M)
    return ((desc.group(1).strip().strip('"\'') if desc else ''),
            (sources.group(1).strip().strip('"\'') if sources else ''))


def summary(desc):
    first = re.split(r'(?<=[.!?])\s', desc, maxsplit=1)[0]
    return first if len(first) <= 170 else first[:167].rstrip() + '...'


def origin(sources):
    corey, ali = 'corey:' in sources, 'ali:' in sources
    return 'Both' if corey and ali else 'Corey Haines' if corey else 'Alireza Rezvani' if ali else '?'


skills = {}
for name in sorted(os.listdir(os.path.join(ROOT, 'skills'))):
    path = os.path.join(ROOT, 'skills', name, 'SKILL.md')
    if os.path.isfile(path):
        skills[name] = read_meta(path)

placed, out = set(), []
for title, names in CATEGORIES + [('Other', sorted(set(skills) - {n for _, ns in CATEGORIES for n in ns}))]:
    rows = [n for n in names if n in skills]
    if not rows:
        continue
    out += [f'### {title}', '', '| Skill | What it does | From |', '|---|---|---|']
    for n in rows:
        desc, sources = skills[n]
        out.append(f'| [`{n}`](skills/{n}/SKILL.md) | {summary(desc).replace("|", "/")} | {origin(sources)} |')
        placed.add(n)
    out.append('')

counts = {k: sum(1 for d, s in skills.values() if origin(s) == k) for k in ('Both', 'Corey Haines', 'Alireza Rezvani')}
header = (f'{len(skills)} skills: {counts["Both"]} merged from both libraries, {counts["Corey Haines"]} from Corey Haines '
          f'only, {counts["Alireza Rezvani"]} from Alireza Rezvani only.')
block = '\n'.join([START, '<!-- Generated by scripts/build_index.py from each SKILL.md. Do not edit by hand. -->', '',
                   header, ''] + out + [END])

readme = open(README, encoding='utf-8').read()
if START not in readme or END not in readme:
    sys.exit('README.md has no SKILLS markers')
readme = readme[:readme.index(START)] + block + readme[readme.index(END) + len(END):]
open(README, 'w', encoding='utf-8').write(readme)
print(header)
